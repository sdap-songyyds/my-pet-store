-- MyPetStore实验一：仅表结构（不含业务数据）
-- 适用：PostgreSQL 16+（本机 18.6）。本文件是 schema.sql（MySQL 8 版）的等价翻译：
--   表、列、主键、唯一键、外键、CHECK、索引、注释一一对应，只换方言。
--   方言差异：AUTO_INCREMENT→GENERATED ... AS IDENTITY，DATETIME→TIMESTAMP，
--   ON UPDATE CURRENT_TIMESTAMP→触发器，COMMENT='...'→COMMENT ON，
--   KEY/UNIQUE KEY→CREATE INDEX/CONSTRAINT，utf8mb4→库级 UTF8 编码，
--   ascii_bin→COLLATE "C"（同样是按字节、区分大小写比较）。
-- 在空的 mypetstore 中首次执行；不DROP、不清空、不覆盖已有表。
-- 已有同名表时会报错，请检查目标数据库，不要用 ON_ERROR_STOP=off 跳过错误。
-- 本文件不创建数据库和角色，见 00-create-role-and-database.sql。
-- 也不由应用启动时自动执行。

SET client_encoding = 'UTF8';
SET TIME ZONE 'Asia/Shanghai';

-- 整个脚本一个事务：任一句失败则全部回滚，不会留下半套表。
BEGIN;

-- PostgreSQL 没有 ON UPDATE CURRENT_TIMESTAMP，用触发器实现同样效果。
-- 只挂到带 updated_at 列的五张表上。
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- ===== 七张表的统一结构开始 =====

-- 1. 教学账号：登录身份与普通用户/管理员角色。
CREATE TABLE store_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username       VARCHAR(50)  NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    display_name   VARCHAR(50)  NOT NULL,
    role           VARCHAR(16)  COLLATE "C" NOT NULL,
    status         VARCHAR(16)  COLLATE "C" NOT NULL DEFAULT 'ENABLED',
    email          VARCHAR(100) NULL,
    phone          VARCHAR(30)  NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_store_user PRIMARY KEY (id),
    CONSTRAINT uk_user_username UNIQUE (username),
    CONSTRAINT ck_user_username   CHECK (char_length(btrim(username)) > 0),
    CONSTRAINT ck_user_password   CHECK (char_length(btrim(password_hash)) > 0),
    CONSTRAINT ck_user_display_name CHECK (char_length(btrim(display_name)) > 0),
    CONSTRAINT ck_user_role       CHECK (role IN ('CUSTOMER', 'ADMIN')),
    CONSTRAINT ck_user_status     CHECK (status IN ('ENABLED', 'DISABLED'))
);

COMMENT ON TABLE  store_user               IS '用户及管理员账号';
COMMENT ON COLUMN store_user.id            IS '内部主键，Java Long';
COMMENT ON COLUMN store_user.username      IS '登录名，创建后不修改，不区分大小写唯一';
COMMENT ON COLUMN store_user.password_hash IS 'BCrypt散列，不保存明文密码';
COMMENT ON COLUMN store_user.display_name  IS '显示名称';
COMMENT ON COLUMN store_user.role          IS 'CUSTOMER或ADMIN';
COMMENT ON COLUMN store_user.status        IS 'ENABLED或DISABLED';

CREATE TRIGGER trg_store_user_updated_at
    BEFORE UPDATE ON store_user
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 2. 两级分类：parent_id为空表示一级；二级必须指向一级，由Service校验。
-- parent_key是生成列：插入/更新实体时不要写入它。
CREATE TABLE category (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code         VARCHAR(32) NOT NULL,
    parent_id    BIGINT      NULL,
    parent_key   BIGINT GENERATED ALWAYS AS (COALESCE(parent_id, 0)) STORED,
    name         VARCHAR(50) NOT NULL,
    sort_order   INT         NOT NULL DEFAULT 0,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_category PRIMARY KEY (id),
    CONSTRAINT uk_category_code UNIQUE (code),
    CONSTRAINT uk_category_sibling_name UNIQUE (parent_key, name),
    CONSTRAINT fk_category_parent FOREIGN KEY (parent_id) REFERENCES category (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_category_code CHECK (char_length(btrim(code)) > 0),
    CONSTRAINT ck_category_name CHECK (char_length(btrim(name)) > 0),
    CONSTRAINT ck_category_sort CHECK (sort_order >= 0)
);

CREATE INDEX idx_category_parent_sort ON category (parent_id, sort_order, id);

COMMENT ON TABLE  category            IS '固定两级商品分类';
COMMENT ON COLUMN category.code       IS '全局唯一编码，创建后不修改';
COMMENT ON COLUMN category.parent_id  IS '一级为空，二级指向一级，创建后不修改';

CREATE TRIGGER trg_category_updated_at
    BEFORE UPDATE ON category
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 3. 一个商品对应一个可销售SKU，不做多规格；下架代替删除。
CREATE TABLE product (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sku          VARCHAR(40)  NOT NULL,
    category_id  BIGINT       NOT NULL,
    name         VARCHAR(120) NOT NULL,
    summary      VARCHAR(500) NULL,
    description  TEXT         NULL,
    cover_image  VARCHAR(255) NOT NULL DEFAULT 'images/logo.png',
    price        NUMERIC(12,2) NOT NULL,
    stock        INT          NOT NULL DEFAULT 0,
    status       VARCHAR(16)  COLLATE "C" NOT NULL DEFAULT 'DRAFT',
    sort_order   INT          NOT NULL DEFAULT 0,
    version      BIGINT       NOT NULL DEFAULT 0,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_product PRIMARY KEY (id),
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES category (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_product_sku    CHECK (char_length(btrim(sku)) > 0),
    CONSTRAINT ck_product_name   CHECK (char_length(btrim(name)) > 0),
    CONSTRAINT ck_product_cover  CHECK (char_length(btrim(cover_image)) > 0),
    CONSTRAINT ck_product_price  CHECK (price > 0),
    CONSTRAINT ck_product_stock  CHECK (stock >= 0),
    CONSTRAINT ck_product_status CHECK (status IN ('DRAFT', 'ON_SALE')),
    CONSTRAINT ck_product_sort   CHECK (sort_order >= 0),
    CONSTRAINT ck_product_version CHECK (version >= 0)
);

CREATE INDEX idx_product_category_status_sort ON product (category_id, status, sort_order, id);
CREATE INDEX idx_product_status_sort          ON product (status, sort_order, id);

COMMENT ON TABLE  product             IS '商品及可销售库存';
COMMENT ON COLUMN product.sku         IS '唯一销售编码，创建后不修改';
COMMENT ON COLUMN product.category_id IS '必须归属二级分类，由Service校验';
COMMENT ON COLUMN product.description IS '纯文本详情，模板转义展示';
COMMENT ON COLUMN product.cover_image IS '站内静态资源相对路径';
COMMENT ON COLUMN product.stock       IS '可销售库存：下单扣减，未支付取消恢复';
COMMENT ON COLUMN product.version     IS '所有商品写操作显式递增，防旧值覆盖';

CREATE TRIGGER trg_product_updated_at
    BEFORE UPDATE ON product
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 4. 图片相册与封面分开；多个商品可复用相同的教学图片。
CREATE TABLE product_image (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id  BIGINT       NOT NULL,
    image_path  VARCHAR(255) NOT NULL,
    alt_text    VARCHAR(120) NULL,
    sort_order  INT          NOT NULL DEFAULT 0,
    CONSTRAINT pk_product_image PRIMARY KEY (id),
    CONSTRAINT fk_image_product FOREIGN KEY (product_id) REFERENCES product (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_image_path CHECK (char_length(btrim(image_path)) > 0),
    CONSTRAINT ck_image_sort CHECK (sort_order >= 0)
);

CREATE INDEX idx_image_product_sort ON product_image (product_id, sort_order, id);

COMMENT ON TABLE product_image IS '商品详情相册';

-- 5. 登录用户的持久购物车：价格不存这里；购物车不占库存。
CREATE TABLE cart_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT    NOT NULL,
    product_id  BIGINT    NOT NULL,
    quantity    INT       NOT NULL DEFAULT 1,
    version     BIGINT    NOT NULL DEFAULT 0,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cart_item PRIMARY KEY (id),
    CONSTRAINT uk_cart_user_product UNIQUE (user_id, product_id),
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES store_user (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_cart_product FOREIGN KEY (product_id) REFERENCES product (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_cart_quantity CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT ck_cart_version  CHECK (version >= 0)
);

CREATE INDEX idx_cart_product ON cart_item (product_id);

COMMENT ON TABLE cart_item IS '按用户持久化的购物车条目';

CREATE TRIGGER trg_cart_item_updated_at
    BEFORE UPDATE ON cart_item
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 6. 订单主表：模拟付款成功即PAID（待发货），没有真实支付渠道或退款。
CREATE TABLE sales_order (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_no          VARCHAR(40)   NOT NULL,
    user_id           BIGINT        NOT NULL,
    status            VARCHAR(16)   COLLATE "C" NOT NULL DEFAULT 'PENDING_PAYMENT',
    total_amount      NUMERIC(12,2) NOT NULL,
    receiver_name     VARCHAR(50)   NOT NULL,
    receiver_phone    VARCHAR(30)   NOT NULL,
    receiver_address  VARCHAR(255)  NOT NULL,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_method    VARCHAR(16)   COLLATE "C" NULL,
    payment_no        VARCHAR(40)   NULL,
    paid_at           TIMESTAMP     NULL,
    cancelled_at      TIMESTAMP     NULL,
    shipped_at        TIMESTAMP     NULL,
    completed_at      TIMESTAMP     NULL,
    CONSTRAINT pk_sales_order PRIMARY KEY (id),
    CONSTRAINT uk_order_no UNIQUE (order_no),
    CONSTRAINT uk_order_payment_no UNIQUE (payment_no),
    CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES store_user (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_order_no CHECK (char_length(btrim(order_no)) > 0),
    CONSTRAINT ck_order_total CHECK (total_amount > 0),
    CONSTRAINT ck_order_receiver CHECK (
        char_length(btrim(receiver_name)) > 0 AND
        char_length(btrim(receiver_phone)) > 0 AND
        char_length(btrim(receiver_address)) > 0
    ),
    CONSTRAINT ck_order_status CHECK (status IN ('PENDING_PAYMENT', 'PAID', 'SHIPPED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_order_payment_info CHECK (
        (status IN ('PENDING_PAYMENT', 'CANCELLED')
            AND payment_method IS NULL AND payment_no IS NULL AND paid_at IS NULL)
        OR
        (status IN ('PAID', 'SHIPPED', 'COMPLETED')
            AND payment_method IS NOT NULL AND payment_method = 'MOCK'
            AND payment_no IS NOT NULL AND char_length(btrim(payment_no)) > 0
            AND paid_at IS NOT NULL)
    ),
    CONSTRAINT ck_order_cancel_time CHECK (
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
        OR (status <> 'CANCELLED' AND cancelled_at IS NULL)
    ),
    CONSTRAINT ck_order_ship_time CHECK (
        (status IN ('SHIPPED', 'COMPLETED') AND shipped_at IS NOT NULL)
        OR (status NOT IN ('SHIPPED', 'COMPLETED') AND shipped_at IS NULL)
    ),
    CONSTRAINT ck_order_complete_time CHECK (
        (status = 'COMPLETED' AND completed_at IS NOT NULL)
        OR (status <> 'COMPLETED' AND completed_at IS NULL)
    ),
    CONSTRAINT ck_order_time_sequence CHECK (
        (paid_at IS NULL OR paid_at >= created_at) AND
        (cancelled_at IS NULL OR cancelled_at >= created_at) AND
        (shipped_at IS NULL OR shipped_at >= paid_at) AND
        (completed_at IS NULL OR completed_at >= shipped_at)
    )
);

CREATE INDEX idx_order_user_created   ON sales_order (user_id, created_at, id);
CREATE INDEX idx_order_status_created ON sales_order (status, created_at, id);

COMMENT ON TABLE  sales_order                  IS '订单及收货、模拟支付信息';
COMMENT ON COLUMN sales_order.order_no         IS '服务端生成的唯一展示订单号';
COMMENT ON COLUMN sales_order.receiver_address IS '下单时完整收货地址快照';
COMMENT ON COLUMN sales_order.payment_method   IS '成功后固定MOCK';
COMMENT ON COLUMN sales_order.payment_no       IS '模拟成功凭证，未支付为空，可空唯一';

CREATE TRIGGER trg_sales_order_updated_at
    BEFORE UPDATE ON sales_order
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 7. 订单明细：保留成交时快照，不随商品后续变化而更新。
CREATE TABLE sales_order_item (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id               BIGINT        NOT NULL,
    product_id             BIGINT        NOT NULL,
    sku_snapshot           VARCHAR(40)   NOT NULL,
    product_name_snapshot  VARCHAR(120)  NOT NULL,
    cover_image_snapshot   VARCHAR(255)  NOT NULL,
    unit_price             NUMERIC(12,2) NOT NULL,
    quantity               INT           NOT NULL,
    line_amount            NUMERIC(12,2) NOT NULL,
    CONSTRAINT pk_sales_order_item PRIMARY KEY (id),
    CONSTRAINT uk_order_item_product UNIQUE (order_id, product_id),
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES sales_order (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_order_item_sku      CHECK (char_length(btrim(sku_snapshot)) > 0),
    CONSTRAINT ck_order_item_name     CHECK (char_length(btrim(product_name_snapshot)) > 0),
    CONSTRAINT ck_order_item_cover    CHECK (char_length(btrim(cover_image_snapshot)) > 0),
    CONSTRAINT ck_order_item_price    CHECK (unit_price > 0),
    CONSTRAINT ck_order_item_quantity CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT ck_order_item_amount   CHECK (line_amount > 0 AND line_amount = unit_price * quantity)
);

CREATE INDEX idx_order_item_product ON sales_order_item (product_id);

COMMENT ON TABLE sales_order_item IS '订单商品快照与金额明细';

-- ===== 七张表的统一结构结束 =====

COMMIT;

